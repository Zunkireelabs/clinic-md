#!/usr/bin/env bash
# Creates LOCAL-ONLY test logins for the seeded org (bright-smile-dental) on the local Supabase
# stack: GoTrue auth user + public.users profile + user_branches grant.
# Passwords are generated here and written to supabase/LOCAL_TEST_USERS.md (gitignored) — they
# are never printed. Re-running reuses existing passwords from that file and is idempotent.
# Refuses to run against anything but the local stack.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
USERS_FILE="$REPO_ROOT/supabase/LOCAL_TEST_USERS.md"

STATUS="$(supabase status -o env 2>/dev/null)"
DB_URL="$(echo "$STATUS" | grep '^DB_URL=' | cut -d= -f2- | tr -d '"')"
API_URL="$(echo "$STATUS" | grep '^API_URL=' | cut -d= -f2- | tr -d '"')"
SERVICE_KEY="$(echo "$STATUS" | grep '^SERVICE_ROLE_KEY=' | cut -d= -f2- | tr -d '"')"
case "$DB_URL$API_URL" in
  *127.0.0.1*127.0.0.1*|*localhost*localhost*) ;;
  *) echo "Refusing to run: stack does not look local." >&2; exit 1 ;;
esac

ORG_ID="00000000-0000-0000-0000-000000000001"
BRANCH_ID="00000000-0000-0000-0000-000000000101"

# email|full name|role
USERS=(
  "admin@clinicmd.test|Local Admin|admin"
  "manager@clinicmd.test|Local Branch Manager|manager"
  "staff@clinicmd.test|Local Front Desk|staff"
)

existing_pw() { [ -f "$USERS_FILE" ] && grep -F "| $1 |" "$USERS_FILE" | awk -F'|' '{gsub(/ |`/,"",$4); print $4}' || true; }

TMP="$(mktemp)"
{
  echo "# Local test users (LOCAL ONLY — gitignored, never commit)"
  echo
  echo "Org: bright-smile-dental · Branch: Kathmandu Main · Login: http://localhost:<port>/bright-smile-dental/login"
  echo "These exist only in the local Docker Supabase (API $API_URL). Regenerated by \`scripts/local-create-test-users.sh\`."
  echo
  echo "| Email | Role | Password |"
  echo "|---|---|---|"
} > "$TMP"

for entry in "${USERS[@]}"; do
  IFS='|' read -r email name role <<< "$entry"
  pw="$(existing_pw "$email")"
  [ -n "$pw" ] || pw="$(openssl rand -base64 18 | tr -dc 'A-Za-z0-9' | head -c 16)Aa1"

  # Create (or update the password of) the GoTrue user via the local admin API.
  uid="$(psql "$DB_URL" -Atc "select id from auth.users where email='$email'")"
  if [ -z "$uid" ]; then
    uid="$(curl -sS -X POST "$API_URL/auth/v1/admin/users" \
      -H "apikey: $SERVICE_KEY" -H "Authorization: Bearer $SERVICE_KEY" -H 'Content-Type: application/json' \
      -d "{\"email\":\"$email\",\"password\":\"$pw\",\"email_confirm\":true}" \
      | python3 -c 'import sys,json; print(json.load(sys.stdin)["id"])')"
  else
    curl -sS -o /dev/null -X PUT "$API_URL/auth/v1/admin/users/$uid" \
      -H "apikey: $SERVICE_KEY" -H "Authorization: Bearer $SERVICE_KEY" -H 'Content-Type: application/json' \
      -d "{\"password\":\"$pw\"}"
  fi

  psql "$DB_URL" -v ON_ERROR_STOP=1 -q <<SQL
insert into public.users (id, email, full_name, role, branch_id, org_id, is_active)
values ('$uid', '$email', '$name', '$role', '$BRANCH_ID', '$ORG_ID', true)
on conflict (id) do update set role = excluded.role, branch_id = excluded.branch_id, org_id = excluded.org_id, is_active = true;
insert into public.user_branches (user_id, branch_id) values ('$uid', '$BRANCH_ID') on conflict do nothing;
SQL
  echo "| $email | $role | \`$pw\` |" >> "$TMP"
done

mv "$TMP" "$USERS_FILE"
echo "==> Local test users ready (see supabase/LOCAL_TEST_USERS.md)"

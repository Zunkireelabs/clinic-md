#!/usr/bin/env bash
# LOCAL ONLY. Sets up the communication hub (migration 013) on the local Supabase stack so it can be tried end to end with the TEST provider:
#   * writes the sender's function URL and bearer token (private.outreach_function_config: the same row the outreach drain uses)
#   * a connected 'test' SMS channel account for the seeded clinic, and a few templates (English and Nepali, one clinical)
#   * the booking-phone consent backfill (idempotent: it only adds missing rows, never touches a STOP)
#   * a gitignored env file for the edge functions with generated secrets (never printed)
# Refuses to run against anything but the local stack. No real SMS gateway is touched.
#
# Then:  supabase functions serve --env-file supabase/functions/.env.hub.local
#        scripts/local-hub-simulate.sh reply +9779800000000 "Thanks, see you"
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$REPO_ROOT/supabase/functions/.env.hub.local"

STATUS="$(supabase status -o env 2>/dev/null)"
DB_URL="$(echo "$STATUS" | grep '^DB_URL=' | cut -d= -f2- | tr -d '"')"
API_URL="$(echo "$STATUS" | grep '^API_URL=' | cut -d= -f2- | tr -d '"')"
case "$DB_URL$API_URL" in
  *127.0.0.1*127.0.0.1*|*localhost*localhost*) ;;
  *) echo "Refusing to run: stack does not look local." >&2; exit 1 ;;
esac

ORG_ID="00000000-0000-0000-0000-000000000001"
# where the database container reaches the functions served on the host (OrbStack / Docker Desktop); override if yours differs
FUNCTION_BASE_URL="${HUB_FUNCTION_BASE_URL:-http://host.docker.internal:55321/functions/v1}"
SENDER="${HUB_TEST_SENDER:-+9779700000001}"

existing() { [ -f "$ENV_FILE" ] && grep "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2- || true; }
CRON_TOKEN="$(existing CRON_BEARER_TOKEN)";        [ -n "$CRON_TOKEN" ]   || CRON_TOKEN="$(openssl rand -hex 24)"
WEBHOOK_SECRET="$(existing HUB_TEST_WEBHOOK_SECRET)"; [ -n "$WEBHOOK_SECRET" ] || WEBHOOK_SECRET="$(openssl rand -hex 24)"

umask 077
{
  echo "# LOCAL ONLY (gitignored). Generated by scripts/local-hub-setup.sh. Never commit."
  echo "CRON_BEARER_TOKEN=$CRON_TOKEN"
  echo "HUB_TEST_WEBHOOK_SECRET=$WEBHOOK_SECRET"
} > "$ENV_FILE"

psql "$DB_URL" -v ON_ERROR_STOP=1 -q <<SQL
delete from private.outreach_function_config;
insert into private.outreach_function_config (function_base_url, cron_bearer_token) values ('$FUNCTION_BASE_URL', '$CRON_TOKEN');

insert into public.channel_accounts (org_id, channel, provider, sender, status, priority, credit_cost_npr)
values ('$ORG_ID', 'sms', 'test', '$SENDER', 'connected', 100, 1.5)
on conflict (provider, sender) do update set status = 'connected', org_id = excluded.org_id;

insert into public.message_templates (org_id, name, channel, language, body, purpose, clinical) values
  ('$ORG_ID', 'booking-confirmation', null, 'en', 'Hi {patient_name}, your {treatment} at {clinic} is on {date} at {time}. Reply STOP to opt out.', 'service', false),
  ('$ORG_ID', 'booking-confirmation', null, 'ne', 'नमस्ते {patient_name}, {clinic} मा तपाईंको {treatment} {date} {time} बजे हो।', 'service', false),
  ('$ORG_ID', 'booking-reminder', null, 'en', 'Reminder: {treatment} at {clinic} on {date} at {time}.', 'service', false),
  ('$ORG_ID', 'post-treatment-check', null, 'en', 'Hi {patient_name}, how is your {treatment} healing?', 'service', true)
on conflict (org_id, name, language, coalesce(channel, 'any')) do nothing;

select public.hub_backfill_booking_consent('$ORG_ID', false);
SQL

echo "==> Hub ready locally. Test sender: $SENDER (provider 'test'). Secrets are in supabase/functions/.env.hub.local (gitignored)."
echo "    Serve the functions:  supabase functions serve --env-file supabase/functions/.env.hub.local"
echo "    The sender runs every minute via pg_cron (hub-send-kick); to run it now:  scripts/local-hub-simulate.sh send"
